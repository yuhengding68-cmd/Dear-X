import type { Entitlement, IapPlatform, Purchase, PurchaseKind } from '../types';

/** Share of a verified purchase that is credited to the creator balance. */
export const CREATOR_SHARE_BPS = 7000;
export const MIN_PAYOUT_CENTS = 1000;
export const MIN_PRICE_CENTS = 100;
export const MAX_PRICE_CENTS = 20000;

export function creatorShareCents(amountCents: number): number {
  return Math.floor((amountCents * CREATOR_SHARE_BPS) / 10000);
}

export function assertPrice(cents: number, paid: boolean): void {
  if (!paid) {
    if (cents !== 0) throw new Error('Free posts cannot have a price.');
    return;
  }
  if (!Number.isInteger(cents) || cents < MIN_PRICE_CENTS || cents > MAX_PRICE_CENTS) {
    throw new Error('Price is outside the allowed range.');
  }
}

/**
 * Stub receipt shape. Real Apple / Google verification replaces this on the server.
 * Tokens are generated by the data layer, never typed by the user.
 */
export function createStubIapToken(): string {
  const id = crypto.randomUUID().replace(/-/g, '');
  return `stub.${id}`;
}

export function assertStubIapToken(token: string): { transactionId: string } {
  if (!/^stub\.[a-z0-9]{16,}$/i.test(token)) {
    throw new Error('IAP stub rejected this receipt.');
  }
  return { transactionId: `stub_txn_${token.slice(5)}` };
}

export function planPurchase(input: {
  userId: string;
  creatorId: string;
  kind: PurchaseKind;
  productId: string;
  amountCents: number;
  platform: IapPlatform;
  token: string;
  now: string;
  alreadyOwned: boolean;
}): { purchase: Purchase; entitlement: Entitlement; creditCents: number } {
  if (input.alreadyOwned) throw new Error('Already purchased.');
  if (input.userId === input.creatorId) throw new Error('You cannot buy your own content.');
  assertPrice(input.amountCents, true);
  const verified = assertStubIapToken(input.token);
  const purchase: Purchase = {
    id: `purchase_${verified.transactionId}`,
    userId: input.userId,
    creatorId: input.creatorId,
    kind: input.kind,
    productId: input.productId,
    amountCents: input.amountCents,
    currency: 'AUD',
    platform: input.platform,
    providerTransactionId: verified.transactionId,
    status: 'completed',
    createdAt: input.now,
  };
  const entitlement: Entitlement = {
    id: `${input.userId}_${input.kind}_${input.productId}`,
    userId: input.userId,
    creatorId: input.creatorId,
    kind: input.kind,
    productId: input.productId,
    active: true,
    createdAt: input.now,
  };
  return { purchase, entitlement, creditCents: creatorShareCents(input.amountCents) };
}

export function formatAud(cents: number, locale: string): string {
  return new Intl.NumberFormat(locale === 'zh-CN' ? 'zh-CN' : 'en-AU', {
    style: 'currency',
    currency: 'AUD',
  }).format(cents / 100);
}
